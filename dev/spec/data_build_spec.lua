-- Tier 1: the shared build step of the data folder
-- (KitnEssentials_Data/DataBuild.lua), and every shipped data file. A stored
-- source is a long string, so the compile smoke cannot see inside it. The tables
-- themselves are never pinned, and the file form is compared with Wrap's output,
-- so any generator is held to one definition.
local lfs = require("lfs")
local Source = dofile("dev/scripts/_data_source.lua")

local ROOT = "KitnEssentials_Data"
local BUILD_FILE = ROOT .. "/DataBuild.lua"
local MISSING = "a data file is missing"
local UNREADABLE = "a data file could not be read"

local function loadInto(ns, path, globals)
    local chunk = assert(loadfile(path))
    local env = { KitnEssentials = { GetNamespace = function() return ns end } }
    for name, value in pairs(globals or {}) do env[name] = value end
    setfenv(chunk, setmetatable(env, { __index = _G }))
    chunk()
end

local function withSources(sources, globals)
    local ns = { DataSources = sources }
    loadInto(ns, BUILD_FILE, globals)
    return ns
end

local function dataFiles()
    local paths = {}
    for entry in lfs.dir(ROOT) do
        local path = ROOT .. "/" .. entry
        if entry:match("%.lua$") and path ~= BUILD_FILE then paths[#paths + 1] = path end
    end
    return paths
end

describe("Data folder build step", function()
    it("builds a table, releases its text, and answers a second call with the same table", function()
        local ns = withSources({ T = "return { a = 1 }" })
        local data = ns.BuildData("T")
        assert.equals(1, data.a)
        assert.is_nil(ns.DataSources.T)
        assert.equals(data, ns.BuildData("T"))
    end)

    it("refuses each bad source with its reason, and keeps the text", function()
        for _, row in ipairs({
            { name = "no such source", sources = {}, reason = MISSING },
            { name = "syntax error", sources = { T = "return {" }, reason = UNREADABLE },
            { name = "raises", sources = { T = "error('x')" }, reason = UNREADABLE },
            { name = "no table", sources = { T = "return 1" }, reason = UNREADABLE },
            { name = "compiler raises", sources = { T = "return {}" }, reason = UNREADABLE,
              globals = { loadstring = function() error("refused") end } },
            -- false, because a nil here would fall through to the real one.
            { name = "no compiler", sources = { T = "return {}" }, reason = UNREADABLE,
              globals = { loadstring = false } },
        }) do
            local text = row.sources.T
            local ns = withSources(row.sources, row.globals)
            local data, reason = ns.BuildData("T")
            assert.is_nil(data, row.name)
            assert.equals(row.reason, reason, row.name)
            assert.equals(text, ns.DataSources.T, row.name)
        end
        local bare = {}
        loadInto(bare, BUILD_FILE)
        local data, reason = bare.BuildData("T")
        assert.is_nil(data)
        assert.equals(MISSING, reason)
    end)

    it("builds every shipped source", function()
        local ns = {}
        loadInto(ns, BUILD_FILE)
        for _, path in ipairs(dataFiles()) do loadInto(ns, path) end
        local names = {}
        for name in pairs(ns.DataSources) do names[#names + 1] = name end
        assert.is_true(#names > 0)
        for _, name in ipairs(names) do
            local data, reason = ns.BuildData(name)
            assert.is_table(data, name .. ": " .. tostring(reason))
        end
    end)

    it("holds every shipped data file to one table, in the form Wrap writes", function()
        for _, path in ipairs(dataFiles()) do
            local file = assert(io.open(path, "rb"))
            local text = file:read("*a"):gsub("\r\n", "\n")
            file:close()
            local ns = {}
            loadInto(ns, path)
            local name, stored = next(ns.DataSources)
            assert.is_nil(next(ns.DataSources, name), path)
            local lines = {}
            for line in stored:gmatch("([^\n]*)\n") do lines[#lines + 1] = line end
            local generatedBy = text:match("Generated by (%S+)%. Do not edit by hand%.")
            assert.is_string(generatedBy, path)
            local want = table.concat(Source.Wrap(name, generatedBy, lines), "\n") .. "\n"
            assert.is_true(want == text, path .. " is not in the form Wrap writes")
        end
    end)
end)
