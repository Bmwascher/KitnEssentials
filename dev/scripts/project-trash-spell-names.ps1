# Projects the verified English spell-name record (JSON) into the Lua data
# file dev/scripts/extract-trash-data.lua reads through --spell-names.
# Deterministic: entries sorted by spell ID, rows by map, NPC and spell ID,
# LF line endings, UTF-8 without a byte-order mark. Writes only the -Out path.
# It validates nothing itself: a malformed record stops it with PowerShell's
# own error, and the generator validates the projected file before any write.
# No network access.
#
#   pwsh -NoProfile -File dev/scripts/project-trash-spell-names.ps1 -Json <record.json> -Out <file.lua>
param(
    [Parameter(Mandatory = $true)][string]$Json,
    [Parameter(Mandatory = $true)][string]$Out
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function ConvertTo-LuaString([string]$Text) {
    return '"' + $Text.Replace('\', '\\').Replace('"', '\"') + '"'
}

$sha = (Get-FileHash -LiteralPath $Json -Algorithm SHA256).Hash.ToLowerInvariant()
$doc = Get-Content -LiteralPath $Json -Raw -Encoding UTF8 | ConvertFrom-Json

$entries = @(foreach ($property in $doc.names.PSObject.Properties) {
    [pscustomobject]@{ Id = [long]$property.Name; Name = [string]$property.Value }
})
$entries = @($entries | Sort-Object -Property Id)

$rows = @(foreach ($row in @($doc.includedRows)) {
    [pscustomobject]@{ Map = [long]$row.mapID; Npc = [long]$row.npcID; Spell = [long]$row.spellID }
})
$rows = @($rows | Sort-Object -Property Map, Npc, Spell)

$ex = @(@($doc.excludedTuple) | ForEach-Object { [long]$_ })

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('-- Generated by dev/scripts/project-trash-spell-names.ps1 from the verified')
$lines.Add('-- English spell-name record. Do not edit; regenerate it instead.')
$lines.Add('return {')
$lines.Add("    sourceSha256 = `"$sha`",")
$lines.Add('    entries = {')
foreach ($entry in $entries) { $lines.Add("        { $($entry.Id), $(ConvertTo-LuaString $entry.Name) },") }
$lines.Add('    },')
$lines.Add('    includedRows = {')
foreach ($row in $rows) { $lines.Add("        { $($row.Map), $($row.Npc), $($row.Spell) },") }
$lines.Add('    },')
$lines.Add('    excludedRows = {')
$lines.Add("        { $($ex[0]), $($ex[1]), $($ex[2]) },")
$lines.Add('    },')
$lines.Add('}')
$text = ($lines -join "`n") + "`n"

$outPath = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Out)
[System.IO.File]::WriteAllText($outPath, $text, [System.Text.UTF8Encoding]::new($false))
Write-Output ('entries {0} rows {1} excluded 1 sha256 {2}' -f $entries.Count, $rows.Count, $sha)
