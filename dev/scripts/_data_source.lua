-- _data_source.lua: the stored form of a table in KitnEssentials_Data, for the
-- dev scripts. A data file holds one table's Lua source as a long string, and
-- KE.BuildData turns it into the table when a module needs it. Loaded by dofile:
--
--   local Source = dofile(_dir .. "_data_source.lua")
--   local lines = Source.Wrap("ScoutSpells", "dev/scripts/derive-scout-spells.lua", sourceLines)
--   local data, err = Source.Read("KitnEssentials_Data/ScoutMobs.lua", "ScoutMobs")
--
-- Wrap returns the whole file as lines, one source line per file line so a
-- table stays diffable, and raises error(msg, 0) for a source line holding the
-- closing long-bracket. Read returns the table, or nil and a message.

local M = {}

local CLOSE = "]==]"

function M.Wrap(name, generatedBy, sourceLines)
    local lines = {
        "local KE = KitnEssentials:GetNamespace()",
        "-- Generated by " .. generatedBy .. ". Do not edit by hand.",
        "",
        "KE.DataSources = KE.DataSources or {}",
        "KE.DataSources." .. name .. " = [==[",
    }
    for _, line in ipairs(sourceLines) do
        if line:find(CLOSE, 1, true) then
            error(name .. " holds " .. CLOSE .. ", which would end its long string", 0)
        end
        lines[#lines + 1] = line
    end
    lines[#lines + 1] = CLOSE
    return lines
end

function M.Read(path, name)
    local chunk, err = loadfile(path)
    if not chunk then return nil, tostring(err) end
    local ns = {}
    setfenv(chunk, { KitnEssentials = { GetNamespace = function() return ns end } })
    local ok, runErr = pcall(chunk)
    if not ok then return nil, tostring(runErr) end
    local source = ns.DataSources and ns.DataSources[name]
    if type(source) ~= "string" then return nil, path .. " does not hold " .. name end
    local build, buildErr = loadstring(source, "=" .. name)
    if not build then return nil, tostring(buildErr) end
    local built, data = pcall(build)
    if not built or type(data) ~= "table" then return nil, name .. " did not build a table" end
    return data
end

return M
